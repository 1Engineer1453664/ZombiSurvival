-- 1. БАЗОВЫЕ НАСТРОЙКИ ОБЪЕКТА
-- Указываем тип энтити "anim" (скриптовый объект с анимациями и моделями, управляемый кодом)
ENT.Type = "anim"
-- Настраиваем режим рендеринга: TRANSLUCENT (разрешает объекту использовать полупрозрачные текстуры/эффекты)
ENT.RenderGroup = RENDERGROUP_TRANSLUCENT

-- 2. ГЕЙМПЛЕЙНЫЕ ПАРАМЕТРЫ ДЛЯ СБОРКИ ZS
-- Разрешает ли инженеру свернуть (упаковать) это поле обратно в инвентарь по кнопке Alt+E
ENT.CanPackUp = true
-- Время в секундах, которое нужно удерживать кнопку, чтобы успешно упаковать коробку
ENT.PackUpTime = 2
-- Максимальный лимит патронов, который физически может вместить в себя бак этой коробки
ENT.MaxAmmo = 350
-- НАШЕ ИЗМЕНЕНИЕ: Меняем базовый хил с 8 на 5, чтобы он совпадал с тем, что мы настроили в оружии
ENT.HealValue = 10
-- Максимальный радиус сканирования вокруг коробки для поиска поврежденных пропов
ENT.MaxDistance = 100

-- 3. ТЕХНИЧЕСКИЕ И БАЛАНСНЫЕ ФЛАГИ ГЕЙММОДА
-- Запрещает размораживать (unfreeze) физику этого объекта, если рядом снимают/удаляют гвозди
ENT.m_NoNailUnfreeze = true
-- Запрещает игрокам прибивать это ремонтное поле гвоздями к другим пропам (чтобы не баговали)
ENT.NoNails = true

-- Пули игроков и зомби будут пролетать сквозь этот объект, не нанося урона (урон идет только от ударов лапами зомби)
ENT.IgnoreBullets = true

-- Указываем гейммоду, что этот объект НЕ является обычной баррикадой (зомби не будут пытаться съесть его в первую очередь)
ENT.IsBarricadeObject = false
-- Разрешает объекту всегда отображать свой зеленый/красный "призрак-проекцию" при попытке установки
ENT.AlwaysGhostable = true

-- 4. СЕТЕВЫЕ ПЕРЕМЕННЫЕ (СИНХРОНИЗАЦИЯ МЕЖДУ СЕРВЕРОМ И КЛИЕНТОМ)
-- Каждая функция Get/Set ниже связывает сервер и клиент, чтобы полоска ХП и патроны отображались у игроков без лагов.

-- Возвращает текущее здоровье коробки, считывая его из сетевой переменной Float (индекс 1)
function ENT:GetObjectHealth()
    return self:GetDTFloat(1)
end

-- Записывает максимальное здоровье коробки в сетевую переменную Float (индекс 2)
function ENT:SetMaxObjectHealth(health)
    self:SetDTFloat(2, health)
end

-- Возвращает максимальное здоровье коробки, считывая его из сетевой переменной Float (индекс 2)
function ENT:GetMaxObjectHealth()
    return self:GetDTFloat(2)
end

-- Возвращает время (CurTime), когда должен произойти следующий импульс починки (индекс 0)
function ENT:GetNextRepairPulse()
    return self:GetDTFloat(0)
end

-- Записывает время следующего импульса починки в сетевую переменную (индекс 0)
function ENT:SetNextRepairPulse(time)
    self:SetDTFloat(0, time)
end

-- Назначает игрока владельцем этой коробки, записывая его в сетевую переменную Entity (индекс 0)
function ENT:SetObjectOwner(owner)
    self:SetDTEntity(0, owner)
end

-- Возвращает игрока, который является текущим владельцем коробки (индекс 0)
function ENT:GetObjectOwner()
    return self:GetDTEntity(0)
end

-- Записывает текущее количество патронов в баке в сетевую переменную Integer (индекс 0)
function ENT:SetAmmo(ammo)
    self:SetDTInt(0, ammo)
end

-- Возвращает текущее количество патронов внутри бака коробки (индекс 0)
function ENT:GetAmmo()
    return self:GetDTInt(0)
end

-- Полностью очищает владельца объекта, заменяя его на NULL (несуществующий объект)
function ENT:ClearObjectOwner()
    self:SetObjectOwner(NULL)
end